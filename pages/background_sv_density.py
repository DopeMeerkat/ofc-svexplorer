@callback(
    Output('bg-density-graph', 'figure'),
    [Input('bg-density-chromosome', 'value'),
     Input('bg-density-y-mode', 'value')],
)
def update_background_sv_density(chrom, y_mode):
    """Update the density graph when chromosome or y-axis mode changes."""
    if not chrom:
        return no_update
    y_mode = y_mode or 'linear'
    return _build_figure(chrom, y_mode)


@callback(
    Output('bg-density-download', 'data'),
    [Input('bg-density-download-button', 'n_clicks')],
    [State('bg-density-chromosome', 'value')],
    prevent_initial_call=True,
)
def download_chromosome_density(n_clicks, chrom):
    """Download all SV-type density segments for the selected chromosome."""
    if not n_clicks or not chrom:
        return no_update
    data = _load_segments(chrom)
    buffer = io.StringIO()
    writer = csv.writer(buffer)
    writer.writerow(['sv_type', 'chrom', 'start', 'end', 'sample_count', 'sample_fraction'])
    for sv_type in SV_TYPES:
        for segment in data.get(sv_type, []):
            writer.writerow([
                segment['sv_type'],
                segment['chrom'],
                segment['start'],
                segment['end'],
                segment['sample_count'],
                f"{segment['sample_fraction']:.6f}",
            ])
    return dict(
        content=buffer.getvalue(),
        filename=f"background_sv_density_{chrom}.csv",
        type='text/csv',
    )
